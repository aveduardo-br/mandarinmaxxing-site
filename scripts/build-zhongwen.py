"""Turns design/zhongwen.svg (中文 drawn as a brush shape) into a grid of tiles for the footer.

Usage: python3 scripts/build-zhongwen.py [cols]
The SVG's paths are flattened, filled (even-odd, so the 口 of 中 keeps its hole) at a high resolution,
and cut into a grid of `cols` columns of square cells; a cell becomes a tile when the shape covers at
least COVER of it. Writes src/data/zhongwen-grid.ts ('#' tile, '.' empty). Like the hero's MANDARIN,
the tiles follow the shape instead of drawing a pixel font. Requires fontTools, Pillow and numpy.
"""
import re
import sys

import numpy as np
from fontTools.pens.recordingPen import RecordingPen
from fontTools.svgLib.path import parse_path
from PIL import Image, ImageChops, ImageDraw

COLS = int(sys.argv[1]) if len(sys.argv) > 1 else 60
COVER = 0.45
SS = 12  # pixels per cell when rasterizing

svg = open('design/zhongwen.svg', encoding='utf-8').read()
vw, vh = map(float, re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg).groups())
cell = vw / COLS
rows = int(np.ceil(vh / cell))
W, H = COLS * SS, rows * SS
k = SS / cell


def subpaths(d):
    pen = RecordingPen()
    parse_path(d, pen)
    polys, cur, last = [], [], (0, 0)
    for op, pts in pen.value:
        if op == 'moveTo':
            cur = [pts[0]]
        elif op == 'lineTo':
            cur.append(pts[0])
        elif op == 'curveTo':
            p0, (p1, p2, p3) = cur[-1], pts
            for i in range(1, 17):
                t = i / 16
                u = 1 - t
                cur.append(tuple(u**3 * a + 3 * u * u * t * b + 3 * u * t * t * c + t**3 * e for a, b, c, e in zip(p0, p1, p2, p3)))
        elif op == 'qCurveTo':
            p0, (p1, p2) = cur[-1], pts[-2:]
            for i in range(1, 13):
                t = i / 12
                u = 1 - t
                cur.append(tuple(u * u * a + 2 * u * t * b + t * t * c for a, b, c in zip(p0, p1, p2)))
        elif op in ('closePath', 'endPath'):
            if len(cur) > 2:
                polys.append(cur)
            cur = []
    return polys


mask = Image.new('1', (W, H), 0)
for d in re.findall(r'<path[^>]* d="([^"]+)"', svg):
    for poly in subpaths(d):
        layer = Image.new('1', (W, H), 0)
        ImageDraw.Draw(layer).polygon([(x * k, y * k) for x, y in poly], fill=1)
        mask = ImageChops.logical_xor(mask, layer)  # even-odd: overlapping subpaths make holes
a = np.array(mask, dtype=float).reshape(rows, SS, COLS, SS).mean(axis=(1, 3))
grid = [''.join('#' if v >= COVER else '.' for v in row) for row in a]
# trim empty rows at the top and bottom
while grid and '#' not in grid[0]:
    grid.pop(0)
while grid and '#' not in grid[-1]:
    grid.pop()
n = sum(r.count('#') for r in grid)
open('src/data/zhongwen-grid.ts', 'w', encoding='utf-8').write(
    '// 中文 in tiles for the footer: design/zhongwen.svg cut into a grid of square cells, a tile where the\n'
    f'// shape covers at least {int(COVER * 100)}% of a cell. {COLS} columns, {len(grid)} rows, {n} tiles. Generated by\n'
    '// scripts/build-zhongwen.py; do not edit by hand.\n'
    'export const ZW_GRID = [\n' + ''.join(f"  '{r}',\n" for r in grid) + '];\n'
)
print(COLS, 'x', len(grid), '→', n, 'tiles')
